"""Regenerates src/lucideWeb.ts: only the lucide icons the app imports, each from its own file.

Run from frontend/ after adding a new `import { X } from 'lucide-react-native'`:
    python scripts/gen-lucide-web.py
"""
import glob
import re

names = set()
files = glob.glob('app/**/*.ts*', recursive=True) + glob.glob('src/**/*.ts*', recursive=True)
for f in files:
    if '__tests__' in f or f.endswith('lucideWeb.ts'):
        continue
    s = open(f, encoding='utf-8').read()
    for m in re.finditer(r"import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*'lucide-react-native'", s):
        for n in m.group(1).split(','):
            n = re.sub(r'^\s*type\s+', '', n).split(' as ')[0].strip()
            if n:
                names.add(n)

# Map every exported name (including aliases) to the file that defines it.
main = open('node_modules/lucide-react-native/dist/esm/lucide-react-native.mjs', encoding='utf-8').read()
file_for = {}
for m in re.finditer(r"export \{([^}]*)\} from '\./icons/([\w.-]+)\.mjs'", main):
    for part in m.group(1).split(','):
        alias = part.strip().split(' as ')[-1].strip()
        if alias:
            file_for[alias] = m.group(2)

missing = sorted(n for n in names if n not in file_for)
if missing:
    raise SystemExit(f'Not found in lucide-react-native: {missing}')

lines = [
    "// Web only: re-exports just the icons the app uses, each from its own file.",
    "// The package's main entry pulls in all ~1,700 icons (about 2 MB of JavaScript). Metro swaps",
    "// this file in for 'lucide-react-native' on web (see metro.config.js).",
    "// Generated by scripts/gen-lucide-web.py: re-run it after adding a new icon import.",
    "",
]
for n in sorted(names):
    lines.append(f"export {{ default as {n} }} from 'lucide-react-native/icons/{file_for[n]}';")
open('src/lucideWeb.ts', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(f'{len(names)} icons written')
